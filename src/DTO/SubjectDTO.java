package DTO;

public class SubjectDTO {
	String subjectName;
	int score;
	
	public SubjectDTO() {
}
	public String getSubjectName() {
		return subjectName;
	}
	public int getScore() {
		return score;
	}
	public void setSubjectName(String subjectName) {
		this.subjectName = subjectName;
	}
	public void setScore(int score) {
		this.score = score;
	}
	
}
